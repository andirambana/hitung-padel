export function fill(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => (vars[key] == null ? "" : String(vars[key])));
}

export function subscribeLang(listener) {
  window.addEventListener(LANG_EVENT, listener);
  return () => window.removeEventListener(LANG_EVENT, listener);
}

export function getLangSnapshot() {
  try {
    const stored = window.localStorage.getItem(LANG_KEY);
    if (stored === "en" || stored === "id") {
      return stored;
    }
    return "id";
  } catch {
    return "id";
  }
}

export function getServerLang() {
  return "id";
}

export function setLang(next) {
  const lang = next === "id" ? "id" : "en";
  window.localStorage.setItem(LANG_KEY, lang);
  window.dispatchEvent(new Event(LANG_EVENT));
}

export function phaseLabel(match, copy) {
  if (match.phase === "tiebreak") {
    return copy.tiebreak;
  }
  if (match.phase === "super") {
    return copy.superPhase;
  }
  if (match.status === "finished") {
    return copy.finished;
  }
  if (match.points[0] >= 3 && match.points[1] >= 3) {
    if (match.rules.deuce === "golden") {
      return copy.goldenPhase;
    }
    if (match.rules.deuce === "star" && match.deuceCount >= 3) {
      return copy.starPhase;
    }
    if (match.advantage == null) {
      return copy.deuce;
    }
    return copy.advantagePhase;
  }
  return fill(copy.game, { n: match.games[0] + match.games[1] + 1 });
}

export function rulesLabel(rules, copy) {
  const deuce = copy.deuceOptions.find((option) => option.id === rules.deuce)?.title ?? copy.goldenPhase;
  const parts = [deuce, rules.bestOf === 1 ? copy.oneSet : copy.bestOf3, fill(copy.games, { n: rules.gamesPerSet })];
  if (rules.superTiebreak) {
    parts.push(copy.superRules);
  }
  return parts.join(" · ");
}

export function momentText(match, event, copy) {
  if (!event) {
    return "";
  }
  const name = match.teams[event.team];
  if (event.kind === "match") {
    return fill(copy.matchWon, { name });
  }
  if (event.kind === "set") {
    return fill(event.side ? copy.setWonSide : copy.setWon, { name });
  }
  if (event.kind === "game") {
    return fill(event.side ? copy.gameWonSide : copy.gameWon, { name });
  }
  if (event.kind === "tiebreak") {
    return copy.tiebreak;
  }
  if (event.kind === "super") {
    return copy.superPhase;
  }
  if (event.kind === "side") {
    return copy.changeEnds;
  }
  return "";
}

export function resultText(match, copy, line) {
  const winner = match.winner == null ? copy.unfinished : fill(copy.won, { name: match.teams[match.winner] });
  return ["HitungSkorPadel", `${match.teams[0]} vs ${match.teams[1]}`, line || copy.noSets, winner, rulesLabel(match.rules, copy)].join("\n");
}
